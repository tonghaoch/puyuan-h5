def dry_shoulders():
    parts = []
    for name in ACTIVE:
        bank = BANKS[name]
        parts.append(f'<g id="sw-{name}-dry-shoulder">')
        color, points = bank['shoulder']
        parts.append(path(rounded_ring(points),color))
        parts.append('</g>')
    return ''.join(parts)


def bank_returns():
    parts = []
    for name in ACTIVE:
        parts.append(f'<g id="sw-{name}-bank-return">')
        for rim, toe, color in BANKS[name]['returns']:
            parts.append(poly(rim+toe[::-1],color))
        parts.append('</g>')
    return ''.join(parts)
